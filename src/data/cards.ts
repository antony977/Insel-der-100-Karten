export const ALL_CARDS: CardDef[] = [...SAMMELKARTEN, ...ZAUBERKARTEN];

const BY_ID = new Map<string, CardDef>(ALL_CARDS.map((c) => [c.id, c]));
const INDEX = new Map<string, number>(ALL_CARDS.map((c, i) => [c.id, i]));

/** Frame-Index einer Karte in den Atlanten 'cards' und 'card-icons' */
export function cardIndex(id: string): number {
  return INDEX.get(id) ?? 0;
}

export function card(id: string): CardDef {
  const c = BY_ID.get(id);
  if (!c) throw new Error(`Unbekannte Karte: ${id}`);
  return c;
}

export function hasCard(id: string): boolean {
  return BY_ID.has(id);
}

/** Anzeige-Nummer: „042" bzw. „Z07" */
export function cardLabel(c: CardDef): string {
  return c.kind === 'sammel' ? `Nr. ${c.id}` : c.id;
}
