function zauber(
  no: number,
  name: string,
  category: SpellCategory,
  rank: Rank,
  limit: number,
  range: SpellRange,
  effect: string,
  glyph: string,
  questOnly = false,
): CardDef {
  const ramp = category === 'angriff' ? 'red' : category === 'abwehr' ? 'teal' : category === 'bewegung' ? 'gold' : 'violet';
  return {
    id: `Z${String(no).padStart(2, '0')}`,
    no,
    kind: 'zauber',
    name,
    rank,
    limit,
    type: 'Zauber',
    text: effect,
    effect,
    hint: questOnly ? 'Nur als Quest-Belohnung erhältlich.' : 'In Siegelpacks im Zauberladen von Runenhall.',
    art: { icon: `g-${glyph}`, c1: ramp },
    unleash: { kind: 'spell' },
    spell: { category, range, questOnly },
  };
}

